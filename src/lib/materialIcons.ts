export function filterMaterialIcons(query: string, limit = 48): string[] {
  const q = query.trim().toLowerCase().replace(/\s+/g, '_');
  if (!q) return SITE_MATERIAL_ICONS.slice(0, limit);
  const starts = SITE_MATERIAL_ICONS.filter((n) => n.startsWith(q));
  const contains = SITE_MATERIAL_ICONS.filter((n) => !n.startsWith(q) && n.includes(q));
  return [...starts, ...contains].slice(0, limit);
}
